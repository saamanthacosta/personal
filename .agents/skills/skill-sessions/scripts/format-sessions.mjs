#!/usr/bin/env node
// Regenerate docs/skill-sessions/INDEX.md from per-run markdown files.
//
// Each input file is expected to start with YAML frontmatter containing
// `skill`, `change`, `branch`, `started_at`, `ended_at`, `status`. This
// script is the only writer of INDEX.md.

import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '..', '..', '..', '..');
const SESSIONS_DIR = process.env.SKILL_SESSIONS_DIR
  ? resolve(process.env.SKILL_SESSIONS_DIR)
  : join(REPO_ROOT, 'docs', 'skill-sessions');
const INDEX_PATH = join(SESSIONS_DIR, 'INDEX.md');

const FRONTMATTER = /^---\n([\s\S]*?)\n---\n/;

function parseFrontmatter(body) {
  const match = body.match(FRONTMATTER);
  if (!match) return null;
  const fields = {};
  for (const line of match[1].split('\n')) {
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    const value = line.slice(idx + 1).trim().replace(/^['"]|['"]$/g, '');
    fields[key] = value;
  }
  return fields;
}

function pickPhaseCount(body) {
  let n = 0;
  for (const line of body.split('\n')) {
    if (/^### Phase /i.test(line)) n += 1;
  }
  return n;
}

async function readSession(file) {
  const raw = await readFile(join(SESSIONS_DIR, file), 'utf8');
  const meta = parseFrontmatter(raw);
  return {
    file,
    relPath: relative(REPO_ROOT, join(SESSIONS_DIR, file)),
    meta: meta ?? {},
    phaseCount: pickPhaseCount(raw),
  };
}

function escapePipes(value) {
  return String(value ?? '').replace(/\|/g, '\\|');
}

async function main() {
  let entries;
  try {
    entries = await readdir(SESSIONS_DIR);
  } catch (err) {
    if (err.code === 'ENOENT') {
      await writeFile(INDEX_PATH, '# Skill sessions\n\n_No sessions recorded yet._\n', 'utf8');
      return;
    }
    throw err;
  }
  const sessions = [];
  for (const entry of entries) {
    if (!entry.endsWith('.md') || entry === 'INDEX.md' || entry === 'README.md') continue;
    sessions.push(await readSession(entry));
  }
  sessions.sort((a, b) => {
    const aStart = a.meta.started_at ?? '';
    const bStart = b.meta.started_at ?? '';
    return bStart.localeCompare(aStart);
  });

  const lines = [
    '# Skill sessions',
    '',
    `Regenerated by \`.agents/skills/skill-sessions/bin/format-sessions.mjs\`. ${sessions.length} session${sessions.length === 1 ? '' : 's'}.`,
    '',
    '| Started | Skill | Change | Branch | Status | Phases | File |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  ];

  if (sessions.length === 0) {
    lines.push('| _no sessions recorded yet_ | | | | | | |');
  } else {
    for (const session of sessions) {
      lines.push(
        `| ${escapePipes(session.meta.started_at ?? '—')} | ${escapePipes(session.meta.skill ?? '—')} | ${escapePipes(session.meta.change ?? '—')} | ${escapePipes(session.meta.branch ?? '—')} | ${escapePipes(session.meta.status ?? '—')} | ${session.phaseCount} | \`${escapePipes(session.relPath)}\` |`,
      );
    }
  }
  lines.push('');
  await writeFile(INDEX_PATH, lines.join('\n'), 'utf8');
  process.stdout.write(`regenerated ${INDEX_PATH} (${sessions.length} sessions)\n`);
}

main().catch((err) => {
  process.stderr.write(`format-sessions: ${err.message}\n`);
  process.exit(1);
});